// Сколько человек (включая Ирину) доживают до финала.
function survivorsAliveCount(state) {
  let n = 1; // Ирина — играбельный персонаж, всегда "жива" по ходу истории
  if (state.flags.doctor_alive) n++;
  if (state.flags.julian_alive) n++;
  if (state.flags.volnov_alive) n++;
  return n;
}

// Есть ли у игрока полный набор улик, доказывающих мотив и личность Марты.
function hasTruthClues(state) {
  const required = ["hidden_journal", "priest_notebook", "newspaper_clipping", "boy_name_full"];
  return required.every((c) => state.clues.includes(c));
}

// Единая точка расчёта: возвращает один из кодов концовки.
//   'madness'  — рассудок героя рухнул ниже критической отметки
//   'solo'     — Ирина осталась совсем одна
//   'wrongful' — обвинён невиновный (доктор или генерал), настоящий убийца
//                остался безнаказан
//   'truth'    — Марта обезврежена, у игрока полные доказательства,
//                подозрение под контролем — лучшая концовка
//   'fragile'  — Марта скрылась/погибла в хаосе, но подозрение среди
//                выживших осталось низким — шаткое, но человеческое доверие
//   'partial'  — все прочие случаи: убийца установлен верно, но либо
//                доказательств недостаточно, либо развязка вышла грязной
function determineEnding(state) {
  if (state.sanity <= 15) return "madness";
  if (survivorsAliveCount(state) <= 1) return "solo";
  if (state.flags.accused_who === "doctor" || state.flags.accused_who === "general") return "wrongful";

  const truthOk =
    hasTruthClues(state) &&
    state.flags.marta_fate === "captured" &&
    state.suspicion <= 45;
  if (truthOk) return "truth";

  // marta_fate === "escaped_violent" всегда сопровождается гибелью обоих
  // спутников (см. scene_052_violent_bad / scene_058_trick_backfire), а
  // значит survivorsAliveCount(state) <= 1 и функция уже вернула бы 'solo'
  // до этой строки. Здесь остаётся только "чистый", ненасильственный побег.
  const fragileOk = state.flags.marta_fate === "escaped" && state.suspicion <= 20;
  if (fragileOk) return "fragile";

  return "partial";
}

